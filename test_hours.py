def main():
    fails = 0
    for code, dtl, now, want, why in CASES:
        got = state(parse(code, dtl), now)[0]
        ok = got == want
        fails += not ok
        print(f'{"통과" if ok else "실패"} [{code or "-"}] {dtl or "(빈 칸)"} @ {now:%a %H:%M} → {got} (기대 {want}) — {why}')
    # 공휴일: 개천절(토) — 공휴일 규칙이 있으면 그걸, "공휴일 휴무"면 닫힘
    s = parse('정시', '(평일)09:00~18:00+(주말)09:00~18:00+(공휴일)10:00~16:00')
    ok1 = state(s, datetime(2026, 10, 3, 9, 30), {HOL})[0] == 'closed' and state(s, datetime(2026, 10, 3, 11), {HOL})[0] == 'open'
    s2 = parse('정시', '09:00~18:00 공휴일 휴무')
    ok2 = state(s2, datetime(2026, 10, 3, 11), {HOL})[0] == 'closed' and state(s2, datetime(2026, 10, 2, 11), {HOL})[0] == 'open'
    for ok, why in ((ok1, '공휴일 시간 따로(10~16시)'), (ok2, '공휴일 휴무')):
        fails += not ok
        print(f'{"통과" if ok else "실패"} {why}')
    n = len(CASES) + 2
    print(f'\n{n - fails}/{n} 통과')
    sys.exit(1 if fails else 0)


if __name__ == '__main__':
    main()
